package outbox

import (
	"fmt"
	"time"
)

// MaxTypeLen is the largest accepted [Message.Type] length. The limit keeps
// the value usable as a bounded-cardinality metric label and as an index key.
const MaxTypeLen = 255

// HeaderTraceParent is the conventional header for a W3C trace context, so a
// message published minutes after it was enqueued can still be linked to the
// transaction that produced it. See [InjectTraceParent].
const HeaderTraceParent = "traceparent"

// Message is an outgoing event as the application supplies it.
//
// Payload serialization is deliberately the application's choice: the outbox
// stores opaque bytes and never inspects them. Set [Message.ContentType] so
// consumers (and the publisher) know how to decode them, and encode a schema
// version in [Message.Type] (for example "orders.created.v2") so the type can
// evolve without ambiguity.
type Message struct {
	// ID uniquely identifies the message. Leave it zero and [NewID] is used.
	// It is stable across every delivery attempt.
	ID ID

	// Type is the event type, required. Prefer a versioned, bounded set of
	// values such as "orders.created.v1": it is used as a metric and log
	// attribute.
	Type string

	// Payload is the serialized event body. It is stored and delivered
	// verbatim and may be empty.
	Payload []byte

	// ContentType describes Payload, for example "application/json". Optional
	// but recommended.
	ContentType string

	// AggregateType and AggregateID record which entity the event belongs to.
	// Both are optional and are carried through to the publisher.
	AggregateType string
	AggregateID   string

	// OrderingKey, when set, groups messages that must be published in
	// enqueue order. It only has an effect on a store configured for ordered
	// delivery; see the package documentation for the exact guarantee.
	OrderingKey string

	// Headers carries small string metadata (correlation ids, tenant,
	// traceparent). It is stored as JSON. Keep it small: it is read on every
	// claim.
	Headers map[string]string

	// AvailableAt delays first delivery until the given instant. Zero means
	// "as soon as possible", and a value in the past is clamped to the
	// store's current time, so a backfill cannot look like a publishing
	// backlog.
	//
	// On a claimed message this field reports when the message became due,
	// which is what makes publication lag measurable.
	AvailableAt time.Time

	// CreatedAt is set by the store at enqueue time and is read-only for
	// callers.
	CreatedAt time.Time
}

// Validate reports whether the message can be enqueued.
func (m Message) Validate() error {
	switch {
	case m.Type == "":
		return fmt.Errorf("%w: type is required", ErrInvalidMessage)
	case len(m.Type) > MaxTypeLen:
		return fmt.Errorf("%w: type is longer than %d bytes", ErrInvalidMessage, MaxTypeLen)
	}
	for k, v := range m.Headers {
		if k == "" {
			return fmt.Errorf("%w: header names must not be empty", ErrInvalidMessage)
		}
		if len(k)+len(v) > 4096 {
			return fmt.Errorf("%w: header %q is too large", ErrInvalidMessage, k)
		}
	}
	return nil
}

// State is the delivery state of a stored message.
type State string

// The delivery states. A message is created Pending, is Leased while a worker
// owns it, and ends either Published or Failed. Failed is terminal until an
// operator requeues it.
const (
	StatePending   State = "pending"
	StateLeased    State = "leased"
	StatePublished State = "published"
	StateFailed    State = "failed"
)

// Claimed is a message leased to a worker for one delivery attempt.
type Claimed struct {
	Message

	// Seq is the store-assigned enqueue sequence number. It orders messages
	// within an ordering key.
	Seq int64

	// Attempt is the number of delivery attempts that have been started,
	// including this one. The first attempt is 1.
	Attempt int

	// LeaseEpoch fences updates: it is incremented every time the message is
	// claimed, and the store rejects writes that carry an older value.
	LeaseEpoch int64

	// LeaseExpiresAt is when the store will let another worker reclaim this
	// message. It is generated by the database clock.
	LeaseExpiresAt time.Time

	// DecodeErr is set when the stored row could not be fully decoded, for
	// example because its headers are not valid JSON. The worker treats such a
	// message as a permanent failure instead of handing a half-built message
	// to the publisher.
	DecodeErr error

	// ReclaimedLease reports that this claim took over a lease that had
	// expired, meaning a previous attempt did not finish cleanly.
	ReclaimedLease bool
}

// Stats is a point-in-time view of the outbox, as returned by
// [Store.Stats]. Counts are exact as of the sampling instant but cost an index
// scan proportional to the number of rows in each state, so they are sampled
// on an interval and never on the publishing path.
type Stats struct {
	// Pending and Leased count unpublished messages. Failed counts terminal
	// failures awaiting operator action.
	Pending int64
	Leased  int64
	Failed  int64

	// OldestPendingAge is how long the oldest *due* pending message has been
	// waiting past its availability time, i.e. publishing lag. It is zero when
	// nothing is due. Messages scheduled for the future do not contribute.
	OldestPendingAge time.Duration

	// ObservedAt is the database time at which the sample was taken.
	ObservedAt time.Time
}

// FailedMessage describes a terminally failed row for operator tooling.
type FailedMessage struct {
	ID          ID
	Type        string
	Attempts    int
	FailedAt    time.Time
	LastError   string
	ErrorKind   string
	Aggregate   string
	OrderingKey string
}
